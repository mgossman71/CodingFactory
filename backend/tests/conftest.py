def wait_for_state(ctx, project_id: str, expected: set[ProjectState], timeout: float = 15.0) -> dict:
    deadline = time.time() + timeout
    last = {}
    while time.time() < deadline:
        resp = ctx.client.get(f"/api/projects/{project_id}")
        assert resp.status_code == 200, resp.text
        last = resp.json()
        if ProjectState(last["state"]) in expected:
            return last
        time.sleep(0.05)
    raise AssertionError(f"project stuck in state {last.get('state')} (error={last.get('error')})")


def create_project(ctx, idea: str = "Build a vehicle maintenance tracker for cars and mowers.") -> str:
    resp = ctx.client.post("/api/projects", json={"idea": idea, "name": "vehicle-maintenance"})
    assert resp.status_code == 201, resp.text
    return resp.json()["id"]


